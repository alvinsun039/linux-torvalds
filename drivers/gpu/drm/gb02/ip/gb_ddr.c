static inline void GB02FUNC72(char value)
{
	u32 data;

	gb_printf(KERN_INFO, "sys_peri 0x%p, peri_base 0x%p, value %d\n",
	 sys_peri_bar, peri_base_bar, value);
	iowrite32(0x60000000, peri_base_bar + 0xD04);
	data = ioread32(mcu_peri_bar + 0x158);
	gb_printf(KERN_DEBUG, "kail1 read 0x158 = 0x%x\n", data);
	if (value == 0)
		iowrite32(0x7C000, mcu_peri_bar + 0x158);
	else if (value == 1) {
		switch (mdev) {
		case 0:
			iowrite32(0xFFFFFFF1, mcu_peri_bar + 0x158);
			break;
		case 1:
			iowrite32(0xFFFFFFF3, mcu_peri_bar + 0x158);
			break;
		case 2:
			iowrite32(0xFFFFFFF7, mcu_peri_bar + 0x158);
			break;
		case 3:
			iowrite32(0xFFFFFFFF, mcu_peri_bar + 0x158);
			break;
		default:
			iowrite32(0xFFFFFFFF, mcu_peri_bar + 0x158);
		}
	}
	data = ioread32(mcu_peri_bar + 0x158);
	gb_printf(KERN_DEBUG, "kail2 read 0x158 = 0x%x\n", data);
}

